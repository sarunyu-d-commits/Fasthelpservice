def md_escape_table(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", "<br>")


def render_markdown() -> str:
    out: list[str] = []
    out.append("# รายงานโครงงาน FastHelp\n")
    out.append("**แพลตฟอร์มเรียกช่างและบริการถึงบ้าน**\n")
    out.append(
        "> เอกสารนี้สร้างจาก `docs/build_report.py` — ไดอะแกรมต้นฉบับอยู่ใน `docs/diagrams/`\n"
    )
    out.append("---\n")
    for block in BLOCKS:
        kind = block["type"]
        if kind == "h1":
            out.append(f"# {block['text']}\n")
        elif kind == "h2":
            out.append(f"## {block['text']}\n")
        elif kind == "h3":
            out.append(f"### {block['text']}\n")
        elif kind == "p":
            out.append(f"{block['text']}\n")
        elif kind == "note":
            out.append(f"> **หมายเหตุ:** {block['text']}\n")
        elif kind == "bullets":
            out.append("\n".join(f"- {item}" for item in block["items"]) + "\n")
        elif kind == "numbers":
            out.append(
                "\n".join(f"{i}. {item}" for i, item in enumerate(block["items"], 1))
                + "\n"
            )
        elif kind == "code":
            out.append(f"```bash\n{block['text']}\n```\n")
        elif kind == "table":
            out.append(f"**{block['caption']}**\n")
            headers = block["headers"]
            out.append("| " + " | ".join(headers) + " |")
            out.append("| " + " | ".join("---" for _ in headers) + " |")
            for row in block["rows"]:
                out.append(
                    "| "
                    + " | ".join(md_escape_table(cell) for cell in row)
                    + " |"
                )
            out.append("")
        elif kind == "figure":
            out.append(f"![{block['caption']}]({block['rel']})\n")
            out.append(f"*{block['caption']}*\n")
        elif kind == "pagebreak":
            out.append("\n---\n")
        elif kind == "toc":
            out.append("*สารบัญ: ดูได้จากไฟล์ Word (.docx) ซึ่งมีสารบัญแบบอัปเดตอัตโนมัติ*\n")
    return "\n".join(out)


