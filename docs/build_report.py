def set_run_font(
    run,
    name: str = THAI_FONT,
    size: float = 11,
    bold: bool | None = None,
    italic: bool | None = None,
    color: RGBColor | None = None,
) -> None:
    run.font.name = name
    run.font.size = Pt(size)
    if bold is not None:
        run.bold = bold
    if italic is not None:
        run.italic = italic
    if color is not None:
        run.font.color.rgb = color
    rpr = run._element.get_or_add_rPr()
    rfonts = rpr.find(qn("w:rFonts"))
    if rfonts is None:
        rfonts = OxmlElement("w:rFonts")
        rpr.append(rfonts)
    rfonts.set(qn("w:ascii"), name)
    rfonts.set(qn("w:hAnsi"), name)
    rfonts.set(qn("w:eastAsia"), name)
    rfonts.set(qn("w:cs"), name)


INLINE_RE = re.compile(r"(\*\*.+?\*\*|`.+?`)")


def add_rich_text(paragraph, text: str, size: float = 11, color: RGBColor = INK) -> None:
    for token in INLINE_RE.split(text):
        if not token:
            continue
        if token.startswith("**") and token.endswith("**"):
            run = paragraph.add_run(token[2:-2])
            set_run_font(run, size=size, bold=True, color=color)
        elif token.startswith("`") and token.endswith("`"):
            run = paragraph.add_run(token[1:-1])
            set_run_font(run, name=MONO_FONT, size=max(size - 1, 8), color=RGBColor(0x00, 0x00, 0x00))
        else:
            parts = token.split("\n")
            for idx, part in enumerate(parts):
                if idx > 0:
                    paragraph.add_run().add_break()
                if part:
                    run = paragraph.add_run(part)
                    set_run_font(run, size=size, color=color)


def add_page_number(paragraph) -> None:
    paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = paragraph.add_run("หน้า ")
    set_run_font(run, size=9, color=GRAY)
    fld = OxmlElement("w:fldSimple")
    fld.set(qn("w:instr"), "PAGE")
    r = OxmlElement("w:r")
    rpr = OxmlElement("w:rPr")
    rfonts = OxmlElement("w:rFonts")
    rfonts.set(qn("w:ascii"), THAI_FONT)
    rfonts.set(qn("w:hAnsi"), THAI_FONT)
    rfonts.set(qn("w:eastAsia"), THAI_FONT)
    rpr.append(rfonts)
    sz = OxmlElement("w:sz")
    sz.set(qn("w:val"), "18")
    rpr.append(sz)
    r.append(rpr)
    t = OxmlElement("w:t")
    t.text = "1"
    r.append(t)
    fld.append(r)
    paragraph._p.append(fld)


def add_bottom_border(paragraph, color: str = "000000", size: int = 8) -> None:
    ppr = paragraph._p.get_or_add_pPr()
    pbdr = OxmlElement("w:pBdr")
    bottom = OxmlElement("w:bottom")
    bottom.set(qn("w:val"), "single")
    bottom.set(qn("w:sz"), str(size))
    bottom.set(qn("w:space"), "4")
    bottom.set(qn("w:color"), color)
    pbdr.append(bottom)
    ppr.append(pbdr)


def add_field_toc(paragraph) -> None:
    paragraph.alignment = WD_ALIGN_PARAGRAPH.LEFT
    run = paragraph.add_run()
    fld_begin = OxmlElement("w:fldChar")
    fld_begin.set(qn("w:fldCharType"), "begin")
    instr = OxmlElement("w:instrText")
    instr.set(qn("xml:space"), "preserve")
    instr.text = r'TOC \o "1-3" \h \z \u'
    fld_sep = OxmlElement("w:fldChar")
    fld_sep.set(qn("w:fldCharType"), "separate")
    placeholder = OxmlElement("w:t")
    placeholder.text = "กด Ctrl+A แล้วกด F9 เพื่ออัปเดตสารบัญ"
    fld_end = OxmlElement("w:fldChar")
    fld_end.set(qn("w:fldCharType"), "end")
    run._r.append(fld_begin)
    run._r.append(instr)
    run._r.append(fld_sep)
    run._r.append(placeholder)
    run._r.append(fld_end)


def shade_cell(cell, hex_fill: str) -> None:
    tc_pr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), hex_fill)
    tc_pr.append(shd)


def repeat_header(row) -> None:
    tr_pr = row._tr.get_or_add_trPr()
    tbl_header = OxmlElement("w:tblHeader")
    tbl_header.set(qn("w:val"), "true")
    tr_pr.append(tbl_header)


def set_table_cell_margins(table, top=50, start=90, bottom=50, end=90) -> None:
    tbl_pr = table._tbl.tblPr
    mar = OxmlElement("w:tblCellMar")
    for key, value in (("top", top), ("start", start), ("bottom", bottom), ("end", end)):
        node = OxmlElement(f"w:{key}")
        node.set(qn("w:w"), str(value))
        node.set(qn("w:type"), "dxa")
        mar.append(node)
    tbl_pr.append(mar)


def add_heading(doc, text: str, level: int) -> None:
    paragraph = doc.add_heading(text, level=level)
    paragraph.paragraph_format.keep_with_next = True
    if level == 1:
        paragraph.paragraph_format.space_before = Pt(6)
        paragraph.paragraph_format.space_after = Pt(10)
        size, color = 17, BLUE
    elif level == 2:
        paragraph.paragraph_format.space_before = Pt(12)
        paragraph.paragraph_format.space_after = Pt(5)
        size, color = 13.5, DARK_BLUE
    else:
        paragraph.paragraph_format.space_before = Pt(9)
        paragraph.paragraph_format.space_after = Pt(4)
        size, color = 12, INK
    for run in paragraph.runs:
        set_run_font(run, size=size, bold=True, color=color)
    paragraph.paragraph_format.line_spacing = 1.15


def add_paragraph(doc, text: str, first: bool = False) -> None:
    paragraph = doc.add_paragraph()
    paragraph.paragraph_format.space_after = Pt(6)
    paragraph.paragraph_format.line_spacing = 1.4
    paragraph.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    add_rich_text(paragraph, text, size=11)


def add_bullets(doc, items: list[str], numbered: bool = False) -> None:
    style = "List Number" if numbered else "List Bullet"
    for item in items:
        paragraph = doc.add_paragraph(style=style)
        paragraph.paragraph_format.space_after = Pt(3)
        paragraph.paragraph_format.line_spacing = 1.35
        paragraph.paragraph_format.left_indent = Cm(0.75)
        add_rich_text(paragraph, item, size=11)


def add_table(doc, block: dict[str, Any]) -> None:
    caption = doc.add_paragraph()
    caption.paragraph_format.space_before = Pt(8)
    caption.paragraph_format.space_after = Pt(4)
    caption.paragraph_format.keep_with_next = True
    run = caption.add_run(block["caption"])
    set_run_font(run, size=9.5, bold=True, color=DARK_BLUE)

    headers = block["headers"]
    rows = block["rows"]
    table = doc.add_table(rows=1, cols=len(headers))
    table.style = "Table Grid"
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.autofit = False
    set_table_cell_margins(table)

    widths = block.get("widths")
    if widths:
        total = sum(widths)
        widths = [w / total * 15.2 for w in widths]

    for idx, header in enumerate(headers):
        cell = table.rows[0].cells[idx]
        cell.text = ""
        p = cell.paragraphs[0]
        p.paragraph_format.space_after = Pt(0)
        run = p.add_run(header)
        set_run_font(run, size=block.get("font_size", 9.5), bold=True, color=INK)
        shade_cell(cell, "E7E7E7")
        if widths:
            cell.width = Cm(widths[idx])
    repeat_header(table.rows[0])

    for row in rows:
        cells = table.add_row().cells
        for idx, value in enumerate(row):
            cells[idx].text = ""
            p = cells[idx].paragraphs[0]
            p.paragraph_format.space_after = Pt(0)
            p.paragraph_format.line_spacing = 1.15
            add_rich_text(p, value, size=block.get("font_size", 9.5))
            if widths:
                cells[idx].width = Cm(widths[idx])

    spacer = doc.add_paragraph()
    spacer.paragraph_format.space_after = Pt(2)


def add_figure(doc, block: dict[str, Any]) -> None:
    path: Path = block["path"]
    if not path.exists():
        raise FileNotFoundError(f"ไม่พบไฟล์ภาพ: {path}")
    paragraph = doc.add_paragraph()
    paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER
    paragraph.paragraph_format.space_before = Pt(8)
    paragraph.paragraph_format.space_after = Pt(3)
    paragraph.paragraph_format.keep_with_next = True
    paragraph.add_run().add_picture(str(path), width=Cm(block["width_cm"]))
    caption = doc.add_paragraph()
    caption.alignment = WD_ALIGN_PARAGRAPH.CENTER
    caption.paragraph_format.space_after = Pt(10)
    run = caption.add_run(block["caption"])
    set_run_font(run, size=9.5, italic=True, color=GRAY)


def add_code_block(doc, text: str) -> None:
    table = doc.add_table(rows=1, cols=1)
    table.style = "Table Grid"
    cell = table.rows[0].cells[0]
    shade_cell(cell, "F7F7F7")
    cell.text = ""
    p = cell.paragraphs[0]
    p.paragraph_format.space_after = Pt(0)
    p.paragraph_format.line_spacing = 1.1
    for idx, line in enumerate(text.split("\n")):
        if idx > 0:
            p.add_run().add_break()
        run = p.add_run(line)
        set_run_font(run, name=MONO_FONT, size=9, color=INK)
    spacer = doc.add_paragraph()
    spacer.paragraph_format.space_after = Pt(2)


def add_note(doc, text: str) -> None:
    table = doc.add_table(rows=1, cols=1)
    table.style = "Table Grid"
    cell = table.rows[0].cells[0]
    shade_cell(cell, "F2F2F2")
    cell.text = ""
    p = cell.paragraphs[0]
    p.paragraph_format.space_after = Pt(0)
    p.paragraph_format.line_spacing = 1.3
    run = p.add_run("หมายเหตุ: ")
    set_run_font(run, size=10, bold=True, color=RGBColor(0x00, 0x00, 0x00))
    add_rich_text(p, text, size=10, color=RGBColor(0x00, 0x00, 0x00))
    spacer = doc.add_paragraph()
    spacer.paragraph_format.space_after = Pt(2)


def set_word2013_compat(doc) -> None:
    """ตั้งค่า compatibilityMode เป็น 15 เพื่อไม่ให้ Word เปิดใน Compatibility Mode"""
    settings = doc.settings.element
    for compat in settings.iter(qn("w:compatSetting")):
        if compat.get(qn("w:name")) == "compatibilityMode":
            compat.set(qn("w:val"), "15")


def build_docx() -> None:
    doc = Document()
    set_word2013_compat(doc)

    section = doc.sections[0]
    section.page_width = Cm(21.0)
    section.page_height = Cm(29.7)
    section.top_margin = Cm(2.54)
    section.bottom_margin = Cm(2.54)
    section.left_margin = Cm(2.54)
    section.right_margin = Cm(2.54)
    section.header_distance = Cm(1.25)
    section.footer_distance = Cm(1.25)
    section.different_first_page_header_footer = True

    props = doc.core_properties
    props.title = "รายงานโครงงาน FastHelp"
    props.subject = "แพลตฟอร์มเรียกช่างและบริการถึงบ้าน"
    props.author = "[ชื่อ-นามสกุล]"
    props.keywords = "FastHelp, Next.js, Supabase, RLS, Expo, PromptPay"

    normal = doc.styles["Normal"]
    normal.font.name = THAI_FONT
    normal.font.size = Pt(11)
    normal.element.rPr.rFonts.set(qn("w:eastAsia"), THAI_FONT)

    header = section.header.paragraphs[0]
    header.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    run = header.add_run("รายงานโครงงาน FastHelp")
    set_run_font(run, size=9, color=GRAY)
    add_bottom_border(header, "BFBFBF", 4)

    add_page_number(section.footer.paragraphs[0])

    # Cover -----------------------------------------------------------------
    for _ in range(3):
        doc.add_paragraph()
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run("รายงานโครงงาน")
    set_run_font(run, size=20, bold=True, color=GRAY)

    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_before = Pt(6)
    run = p.add_run("FastHelp")
    set_run_font(run, size=44, bold=True, color=BLUE)

    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run("แพลตฟอร์มเรียกช่างและบริการถึงบ้าน")
    set_run_font(run, size=18, bold=True, color=INK)

    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run("On-Demand Home Service Platform")
    set_run_font(run, size=13, italic=True, color=GRAY)
    add_bottom_border(p, "000000", 6)

    for _ in range(3):
        doc.add_paragraph()

    details = [
        ("จัดทำโดย", "[ชื่อ-นามสกุล]"),
        ("รหัสนักศึกษา", "[xxxxxxxx]"),
        ("อาจารย์ที่ปรึกษา", "[ชื่อ-นามสกุล]"),
        ("หลักสูตร", "[ชื่อหลักสูตร]"),
        ("สาขาวิชา", "[ชื่อสาขาวิชา]"),
        ("คณะ / สถาบัน", "[ชื่อคณะ / สถาบัน]"),
        ("ปีการศึกษา", "2569"),
    ]
    for label, value in details:
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.space_after = Pt(2)
        run = p.add_run(f"{label}  ")
        set_run_font(run, size=11, bold=True, color=GRAY)
        run = p.add_run(value)
        set_run_font(run, size=12, color=INK)

    doc.add_page_break()

    # Body ------------------------------------------------------------------
    for block in BLOCKS:
        kind = block["type"]
        if kind == "h1":
            if block["text"] == "สารบัญ":
                # สารบัญไม่ควรอยู่ในสารบัญเอง
                p = doc.add_paragraph()
                p.alignment = WD_ALIGN_PARAGRAPH.CENTER
                p.paragraph_format.space_after = Pt(12)
                run = p.add_run("สารบัญ")
                set_run_font(run, size=18, bold=True, color=BLUE)
                add_field_toc(doc.add_paragraph())
            else:
                add_heading(doc, block["text"], 1)
        elif kind == "h2":
            add_heading(doc, block["text"], 2)
        elif kind == "h3":
            add_heading(doc, block["text"], 3)
        elif kind == "p":
            add_paragraph(doc, block["text"])
        elif kind == "note":
            add_note(doc, block["text"])
        elif kind == "bullets":
            add_bullets(doc, block["items"], numbered=False)
        elif kind == "numbers":
            add_bullets(doc, block["items"], numbered=True)
        elif kind == "table":
            add_table(doc, block)
        elif kind == "figure":
            add_figure(doc, block)
        elif kind == "code":
            add_code_block(doc, block["text"])
        elif kind == "pagebreak":
            doc.add_page_break()
        elif kind == "toc":
            pass

    doc.save(DOCX_PATH)


def main() -> None:
    DOCS.mkdir(exist_ok=True)
    md = render_markdown()
    MD_PATH.write_text(md, encoding="utf-8")
    build_docx()
    print(f"Markdown: {MD_PATH}")
    print(f"Word:     {DOCX_PATH}")
    print(f"Blocks:   {len(BLOCKS)}")


if __name__ == "__main__":
    main()
