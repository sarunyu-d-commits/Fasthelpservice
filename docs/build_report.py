BLOCKS: list[dict[str, Any]] = []


def H1(text: str) -> None:
    BLOCKS.append({"type": "h1", "text": text})


def H2(text: str) -> None:
    BLOCKS.append({"type": "h2", "text": text})


def H3(text: str) -> None:
    BLOCKS.append({"type": "h3", "text": text})


def P(text: str) -> None:
    BLOCKS.append({"type": "p", "text": text})


def BULLETS(items: list[str]) -> None:
    BLOCKS.append({"type": "bullets", "items": items})


def NUMBERS(items: list[str]) -> None:
    BLOCKS.append({"type": "numbers", "items": items})


def NOTE(text: str) -> None:
    BLOCKS.append({"type": "note", "text": text})


def CODE(text: str) -> None:
    BLOCKS.append({"type": "code", "text": text.strip("\n")})


def TABLE(
    caption: str,
    headers: list[str],
    rows: list[list[str]],
    widths: list[float] | None = None,
    font_size: float = 9.5,
) -> None:
    BLOCKS.append(
        {
            "type": "table",
            "caption": caption,
            "headers": headers,
            "rows": rows,
            "widths": widths,
            "font_size": font_size,
        }
    )


def FIGURE(filename: str, caption: str, width_cm: float = 15.4) -> None:
    BLOCKS.append(
        {
            "type": "figure",
            "path": DIAGRAMS / filename,
            "rel": f"diagrams/{filename}",
            "caption": caption,
            "width_cm": width_cm,
        }
    )


def PAGEBREAK() -> None:
    BLOCKS.append({"type": "pagebreak"})


